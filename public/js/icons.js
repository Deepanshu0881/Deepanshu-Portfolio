export function icon(name, cls = '') {
  const body = STROKE[name];
  if (!body) return '';
  return `<svg class="i ${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

export function brandIcon(name, cls = '') {
  const d = BRAND[name];
  if (!d) return '';
  return `<svg class="i ${cls}" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"><path d="${d}"/></svg>`;
}

/** Icon markup for a social platform. Unknown brands render a link icon that the client upgrades from Simple Icons. */
export function socialIcon(platform) {
  const meta = SOCIALS[platform] || SOCIALS.other;
  if (meta.brand) return brandIcon(meta.brand);
  if (meta.slug) return `<span class="si" data-icon="${meta.slug}">${icon('link')}</span>`;
  return icon(meta.stroke);
}
